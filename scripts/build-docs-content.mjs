/*
 * Build-time generator (docs-plan.md §3.2): compiles docs/product Markdown
 * into a plain JS module that ships inside the server bundle. The deployed
 * Cloudflare worker has no filesystem and cannot see the repo's docs tree,
 * so runtime fs reads 500 in production - the loader must consume this
 * generated module instead. Run automatically by the web `prebuild` hook.
 */
import { readdir as readdirCb, readFile as readFileCb, writeFileSync } from "node:fs";
import { promisify } from "node:util";
const readdir = promisify(readdirCb);
const readFile = promisify(readFileCb);
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PRODUCT = path.join(ROOT, "docs", "product");
const OUT = path.join(ROOT, "apps", "web", "lib", "docs-content.generated.mjs");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else if (entry.name.endsWith(".md")) files.push(full);
  }
  return files.sort();
}

async function main() {
  const files = await walk(PRODUCT);
  const pages = [];
  for (const full of files) {
    const body = await readFile(full, { encoding: "utf8" });
    const slug = path.relative(PRODUCT, full).replace(/\.md$/, "").replaceAll("\\", "/");
    pages.push({ slug, body });
  }
  const banner = `/*
 * Generated by scripts/build-docs-content.mjs from docs/product - DO NOT EDIT.
 * Source of truth: the Markdown files; regenerate via \`pnpm docs:content\`.
 */`;
  const module = `${banner}\nexport const DOCS_RAW = ${JSON.stringify(pages)};\n`;
  writeFileSync(OUT, module);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${pages.length} pages)`);
}

await main();
