/*
 * Generated docs reference (docs-plan.md §7 Docs-C). Builds two reference
 * pages from machine sources so the browsable docs can never drift:
 *
 *   reference/api-endpoints.generated.md        <- apps/api-edge/openapi.json
 *   reference/protocol-vocabularies.generated.md <- packages/protocol/src enums
 *
 * `node scripts/generate-docs-reference.mjs` writes them;
 * `node scripts/generate-docs-reference.mjs --check` fails when the files on
 * disk differ (CI dirty-diff gate). Generated pages carry status: current and
 * a sourceOfTruth pointing at the machine source - edit the source, rerun.
 */
import { readFile, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { readFile as readFileAsync } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const OUT_DIR = path.join(ROOT, "docs", "product", "reference");
const CHECK = process.argv.includes("--check");

const HEADER = (source, generatedNote) => `---
title: ${generatedNote.title}
description: ${generatedNote.description}
audience: agent-developer
status: current
sourceOfTruth: ${source}
updatedAt: ${generatedNote.updatedAt}
---

<!-- Generated by scripts/generate-docs-reference.mjs. Edit the source, not this file. -->
`;

function apiEndpointsPage(openapi) {
  const entries = [];
  for (const [route, methods] of Object.entries(openapi.paths ?? {})) {
    for (const [method, spec] of Object.entries(methods)) {
      if (!["get", "post", "put", "delete", "patch"].includes(method)) continue;
      entries.push({ method: method.toUpperCase(), route, summary: spec.summary ?? spec.description ?? "", operationId: spec.operationId ?? "" });
    }
  }
  entries.sort((a, b) => a.route.localeCompare(b.route) || a.method.localeCompare(b.method));

  const groups = new Map();
  for (const entry of entries) {
    const segment = entry.route.split("/").filter(Boolean)[0] ?? "root";
    if (!groups.has(segment)) groups.set(segment, []);
    groups.get(segment).push(entry);
  }

  const lines = [
    `${entries.length} endpoints across ${groups.size} resource groups, generated from the OpenAPI contract. Authentication, pagination, and error shape are described in [API reference](/docs/reference/api).`,
  ];
  for (const [group, items] of groups) {
    lines.push("", `## ${group}`, "");
    lines.push("| Method | Path | Summary |", "| --- | --- | --- |");
    for (const item of items) {
      lines.push(`| \`${item.method}\` | \`${item.route}\` | ${item.summary.replaceAll("|", "\\|")} |`);
    }
  }
  return lines.join("\n") + "\n";
}

async function protocolVocabulariesPage() {
  const protocol = (relative) => path.join(ROOT, "packages", "protocol", "src", relative);
  const { CLAIM_STATES } = await importProtocol("claim-state.mjs");
  const { CLAIM_RELATION_TYPES } = await importProtocol("claim-relation.mjs");
  const roleModule = await importProtocol("contribution-role.mjs");
  const { CONTRIBUTION_ROLES } = roleModule;
  const ROLE_SEMANTICS = roleModule.default ?? roleModule.ROLE_SEMANTICS ?? null;
  const receiptSource = await readFileAsync(protocol("verification-receipt.mjs"), "utf8");
  const outcomes = receiptSource.match(/const VERIFICATION_OUTCOMES = Object\.freeze\(\[([^\]]+)\]\)/)?.[1]
    .split(",").map((value) => value.trim().replaceAll("'", "")) ?? [];
  const challengeSource = await readFileAsync(protocol("challenge-state.mjs"), "utf8");
  const challengeStates = challengeSource.match(/const CHALLENGE_STATES = Object\.freeze\(\[([^\]]*)\]/s)?.[1]
    .split(",").map((value) => value.trim().replaceAll("'", "")).filter(Boolean) ?? [];

  const section = (title, values, source) => [
    `## ${title}`, "",
    `Source: \`${source}\` - ${values.length} values.`, "",
    ...values.map((value) => `- \`${value}\``), "",
  ];

  return [
    ...section("Claim states", CLAIM_STATES, "packages/protocol/src/claim-state.mjs"),
    ...section("Claim graph relation types", CLAIM_RELATION_TYPES, "packages/protocol/src/claim-relation.mjs"),
    ...section("Challenge states", challengeStates, "packages/protocol/src/challenge-state.mjs"),
    ...section("Verification receipt outcomes", outcomes, "packages/protocol/src/verification-receipt.mjs"),
    ...section("Contribution roles", CONTRIBUTION_ROLES.map((role) => ROLE_SEMANTICS ? `${role} - ${ROLE_SEMANTICS[role]}` : role), "packages/protocol/src/contribution-role.mjs"),
  ].join("\n");
}

async function importProtocol(relative) {
  const { pathToFileURL } = await import("node:url");
  return import(pathToFileURL(path.join(ROOT, "packages", "protocol", "src", relative)).href);
}

/** Deterministic last-commit date for a file or directory (YYYY-MM-DD). */
function gitDate(target) {
  const result = spawnSync("git", ["log", "-1", "--format=%cs", "--", target], { encoding: "utf8" });
  const date = (result.stdout ?? "").trim();
  return date || new Date().toISOString().slice(0, 10);
}

async function main() {
  const openapi = JSON.parse(await readFileAsync(path.join(ROOT, "apps", "api-edge", "openapi.json"), "utf8"));
  const targets = [
    {
      file: path.join(OUT_DIR, "api-endpoints.generated.md"),
      updatedAt: gitDate(path.join(ROOT, "apps", "api-edge", "openapi.json")),
      get header() {
        return HEADER("apps/api-edge/openapi.json", {
          title: "API endpoints (generated)",
          description: "Every endpoint in the OpenAPI contract, grouped by resource. Generated - do not edit.",
          updatedAt: this.updatedAt,
        });
      },
      body: apiEndpointsPage(openapi),
    },
    {
      file: path.join(OUT_DIR, "protocol-vocabularies.generated.md"),
      updatedAt: gitDate(path.join(ROOT, "packages", "protocol", "src")),
      get header() {
        return HEADER("packages/protocol/src", {
          title: "Protocol vocabularies (generated)",
          description: "Every protocol status and relation enum, imported from the protocol source. Generated - do not edit.",
          updatedAt: this.updatedAt,
        });
      },
      body: await protocolVocabulariesPage(),
    },
  ];

  let dirty = false;
  for (const target of targets) {
    const contents = target.header + "\n" + target.body;
    let existing = null;
    try {
      existing = await readFileAsync(target.file, "utf8");
    } catch { /* first generation */ }
    if (existing === contents) {
      console.log(`ok  ${path.relative(ROOT, target.file)} (up to date)`);
      continue;
    }
    dirty = true;
    if (CHECK) {
      console.error(`dirty ${path.relative(ROOT, target.file)} - run \`node scripts/generate-docs-reference.mjs\` and commit`);
      continue;
    }
    writeFileSync(target.file, contents);
    console.log(`wrote ${path.relative(ROOT, target.file)}`);
  }
  if (CHECK && dirty) process.exit(1);
}

await main();
